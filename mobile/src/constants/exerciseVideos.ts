export function getExerciseVideoUrl(exerciseName: string): string | undefined {
  if (EXERCISE_VIDEO_LINKS[exerciseName]) {
    return EXERCISE_VIDEO_LINKS[exerciseName];
  }
  // Busca flexível ignorando caixa ou pequenas variações
  const clean = exerciseName.toLowerCase().trim();
  for (const [name, url] of Object.entries(EXERCISE_VIDEO_LINKS)) {
    if (clean.includes(name.toLowerCase()) || name.toLowerCase().includes(clean)) {
      return url;
    }
  }
  return undefined;
}
